def format_training_data(examples: List[Tuple[str, str]], style: str) -> List[Dict]:
    """Форматируем данные для обучения"""
    
    formatted_data = []
    
    for original, styled in examples:
        # Создаём обучающий пример в формате:
        # "Стиль пират: Привет -> Йо-хо-хо"
        
        training_text = f"Стиль {style}: {original} -> {styled}"
        
        formatted_data.append({
            "text": training_text,
            "style": style,
            "original": original,
            "styled": styled
        })
    
    return formatted_data

def create_all_training_data():
    """Создаём все тренировочные данные"""
    
    print("🎭 Создаём тренировочные данные...")
    
    # Собираем примеры для всех стилей
    pirate_examples = create_pirate_examples()
    robot_examples = create_robot_examples()
    gangster_examples = create_gangster_examples()
    
    print(f"🏴‍☠️ Пиратских примеров: {len(pirate_examples)}")
    print(f"🤖 Роботских примеров: {len(robot_examples)}")
    print(f"😎 Гангстерских примеров: {len(gangster_examples)}")
    
    # Форматируем данные
    all_data = []
    all_data.extend(format_training_data(pirate_examples, "пират"))
    all_data.extend(format_training_data(robot_examples, "робот"))
    all_data.extend(format_training_data(gangster_examples, "гангстер"))
    
    # Перемешиваем
    random.shuffle(all_data)
    
    print(f"📊 Всего примеров: {len(all_data)}")
    
    # Сохраняем
    output_file = "./training_data/style_examples.json"
    import os
    os.makedirs("./training_data", exist_ok=True)
    
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(all_data, f, ensure_ascii=False, indent=2)
    
    print(f"💾 Данные сохранены в: {output_file}")
    
    # Показываем примеры
    print("\n📋 ПРИМЕРЫ ДАННЫХ:")
    print("=" * 50)
    for i, example in enumerate(all_data[:5]):
        print(f"{i+1}. {example['text']}")
    
    return all_data

def validate_training_data():
    """Проверяем качество данных"""
    
    print("\n🔍 ПРОВЕРКА КАЧЕСТВА ДАННЫХ:")
    print("=" * 50)
    
    with open("./training_data/style_examples.json", 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    # Статистика по стилям
    styles = {}
    for item in data:
        style = item['style']
        styles[style] = styles.get(style, 0) + 1
    
    print("📊 Распределение по стилям:")
    for style, count in styles.items():
        print(f"   {style}: {count} примеров")
    
    # Проверяем длину примеров
    lengths = [len(item['text']) for item in data]
    avg_length = sum(lengths) / len(lengths)
    
    print(f"\n📏 Средняя длина примера: {avg_length:.1f} символов")
    print(f"📏 Самый короткий: {min(lengths)} символов")
    print(f"📏 Самый длинный: {max(lengths)} символов")
    
    # Показываем случайные примеры
    print(f"\n🎲 СЛУЧАЙНЫЕ ПРИМЕРЫ:")
    random_examples = random.sample(data, 3)
    for i, ex in enumerate(random_examples, 1):
        print(f"{i}. {ex['text']}")

