    def replace_words_pirate_style(self, text: str) -> str:
        """Заменяет обычные слова на пиратские"""
        result = text
        for normal, pirate in self.pirate_words['замены'].items():
            result = result.replace(normal, pirate)
        return result

    def add_pirate_ending(self, text: str) -> str:
        """Добавляет пиратское окончание"""
        ending = random.choice(self.pirate_words['концовки'])
        return text + ending

    def generate_from_templates(self) -> List[Tuple[str, str]]:
        """Генерирует фразы из шаблонов"""
        examples = []
        
        for template in self.sentence_templates:
            # Находим все переменные в шаблоне
            import re
            variables = re.findall(r'\{(\w+)\}', template)
            
            # Генерируем несколько вариантов для каждого шаблона
            for _ in range(5):  # 5 вариантов на шаблон
                try:
                    # Подставляем случайные значения
                    substitutions = {}
                    for var in variables:
                        if var in self.word_sets:
                            substitutions[var] = random.choice(self.word_sets[var])
                    
                    if substitutions:  # Если есть что подставлять
                        normal_text = template.format(**substitutions)
                        pirate_text = self.replace_words_pirate_style(normal_text)
                        pirate_text = self.add_pirate_ending(pirate_text)
                        
                        examples.append((normal_text, pirate_text))
                except KeyError:
                    continue  # Пропускаем если нет подходящих слов
        
        return examples

