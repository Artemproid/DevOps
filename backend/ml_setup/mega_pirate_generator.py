def create_mega_pirate_dataset():
    """Создаёт мега-датасет для обучения"""
    
    generator = PirateMegaGenerator()
    examples = generator.generate_mega_dataset()
    
    # Форматируем для JSON
    formatted_data = []
    for normal, pirate in examples:
        formatted_data.append({
            "text": f"Стиль пират: {normal} -> {pirate}",
            "style": "пират", 
            "original": normal,
            "styled": pirate
        })
    
    # Перемешиваем
    random.shuffle(formatted_data)
    
    # Сохраняем
    import os
    os.makedirs("./training_data", exist_ok=True)
    
    output_file = "./training_data/mega_pirate_dataset.json"
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(formatted_data, f, ensure_ascii=False, indent=2)
    
    print(f"\n💾 СОХРАНЕНО В: {output_file}")
    
    # Показываем примеры
    print(f"\n🎲 СЛУЧАЙНЫЕ ПРИМЕРЫ:")
    print("=" * 70)
    for i, example in enumerate(random.sample(formatted_data, min(15, len(formatted_data)))):
        print(f"{i+1:2d}. {example['original']} -> {example['styled']}")
    
    return formatted_data

